// Downloads PMDCollab SpriteCollab sprites (CC BY-NC 4.0) for every species in the content,
// writes frame metadata to src/content/sprites.json and the per-artist credits to CREDITS.md.
// Usage: node tools/fetch-sprites.mjs && python3 tools/pack-sprites.py   (needs network access to raw.githubusercontent.com)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master";
const OUT = "src/assets/sprites";
const ANIMS = ["Idle", "Walk", "Hurt"];
const species = JSON.parse(readFileSync("src/content/species.json", "utf8"));

async function get(path, type = "text") {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return type === "text" ? res.text() : Buffer.from(await res.arrayBuffer());
}

/** Minimal AnimData.xml reader: name → { frameWidth, frameHeight, durations } following CopyOf links. */
function parseAnimData(xml) {
  const anims = {};
  for (const block of xml.split("<Anim>").slice(1)) {
    const tag = (t) => block.match(new RegExp(`<${t}>([^<]*)</${t}>`))?.[1];
    anims[tag("Name")] = {
      copyOf: tag("CopyOf"),
      frameWidth: Number(tag("FrameWidth")),
      frameHeight: Number(tag("FrameHeight")),
      durations: [...block.matchAll(/<Duration>(\d+)<\/Duration>/g)].map((m) => Number(m[1])),
    };
  }
  const resolve = (name) => (anims[name]?.copyOf ? resolve(anims[name].copyOf) : name);
  return { anims, resolve };
}

// credits.txt lines name artists by their Discord id (or a plain name); index both.
const names = new Map();
for (const [name, discord, contact] of (await get("credit_names.txt")).split("\n").slice(1).map((l) => l.split("\t"))) {
  if (!name && !discord) continue;
  const entry = { name: name || `Unnamed artist (Discord ${discord.replace(/[<@!>]/g, "")})`, contact: contact?.trim() ?? "" };
  if (name) names.set(name, entry);
  if (discord) names.set(discord, entry);
}
const authorsOf = (creditsTxt) => [...new Set(creditsTxt.split("\n").filter(Boolean).map((l) => l.split("\t")[1]))];

mkdirSync(OUT, { recursive: true });
const meta = {};
const credits = new Map(); // author → Set of Pokémon names
for (const s of Object.values(species)) {
  const id = String(s.dex).padStart(4, "0");
  const { anims, resolve } = parseAnimData(await get(`sprite/${id}/AnimData.xml`));
  meta[s.id] = { dex: s.dex };
  for (const anim of ANIMS) {
    const real = resolve(anim);
    const a = anims[real];
    writeFileSync(`${OUT}/${id}-${anim.toLowerCase()}.png`, await get(`sprite/${id}/${real}-Anim.png`, "bin"));
    meta[s.id][anim.toLowerCase()] = { frameWidth: a.frameWidth, frameHeight: a.frameHeight, durations: a.durations };
  }
  writeFileSync(`${OUT}/${id}-portrait.png`, await get(`portrait/${id}/Normal.png`, "bin"));
  for (const who of [...authorsOf(await get(`sprite/${id}/credits.txt`)), ...authorsOf(await get(`portrait/${id}/credits.txt`))]) {
    if (!credits.has(who)) credits.set(who, new Set());
    credits.get(who).add(s.name);
  }
  console.log(`${s.name} (#${s.dex})`);
}
writeFileSync("src/content/sprites.json", JSON.stringify(meta, null, 1) + "\n");

const rows = [...credits.entries()]
  .map(([who, mons]) => {
    const n = names.get(who) ?? { name: who.startsWith("<@") ? `Unnamed artist (Discord ${who.replace(/[<@!>]/g, "")})` : who, contact: "" };
    const contact = /^https?:\/\//.test(n.contact) ? n.contact : "";
    return `| ${n.name} | ${contact} | ${[...mons].sort().join(", ")} |`;
  })
  .sort();
writeFileSync("CREDITS.md", `# Credits

## Pokémon sprites and portraits

From the [PMDCollab SpriteCollab](https://github.com/PMDCollab/SpriteCollab) project, used under
[CC BY-NC 4.0](https://creativecommons.org/licenses/by-nc/4.0/) (non-commercial, with attribution).
Sprites credited to CHUNSOFT are from *Pokémon Mystery Dungeon*; the licence only covers the rights of the
community artists, and Pokémon designs remain the property of Nintendo, Game Freak, Creatures Inc. and
The Pokémon Company. Generated by \`tools/fetch-sprites.mjs\`.

| Artist | Contact | Pokémon |
|---|---|---|
${rows.join("\n")}
`);
console.log(`credits: ${rows.length} artists`);
